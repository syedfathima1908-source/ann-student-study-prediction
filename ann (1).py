import pandas as pd
import torch
import torch.nn as nn

data=pd.read_csv("student_dataset_10000_rows.csv")

data

ip=torch.tensor(data['sleep_hours'].values,dtype=torch.float32).reshape(-1,1)
op=torch.tensor(data['study_hours'].values,dtype=torch.float32).reshape(-1,1)

model=nn.Linear(1,1)

error=nn.MSELoss()

opt=torch.optim.SGD(model.parameters(),lr=0.001)

for i in range(1000):
  pred = model(ip)
  loss = error(pred , op)

  opt.zero_grad()
  loss.backward()
  opt.step()

print(model(torch.tensor([[3.0]])))

